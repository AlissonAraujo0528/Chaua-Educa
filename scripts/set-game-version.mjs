import {readFileSync,writeFileSync} from 'node:fs';
const version=process.argv[2];
if(!/^(0|[1-9]\d*)\.(0|[1-9]\d*)\.(0|[1-9]\d*)$/.test(version??''))
 throw new Error('Informe a versão no formato 1.0.1');
const root=new URL('../',import.meta.url);
for(const file of ['package.json','package-lock.json']){
 const path=new URL(file,root),data=JSON.parse(readFileSync(path,'utf8'));
 data.version=version;
 if(file==='package-lock.json')data.packages[''].version=version;
 writeFileSync(path,JSON.stringify(data,null,2)+'\n');
}
writeFileSync(new URL('Chaua-Educa-main/js/version.mjs',root),
 `// Generated by scripts/set-game-version.mjs; keep package and runtime aligned.\nexport const GAME_VERSION='${version}';\n`);
console.log(`Versão do pacote, lockfile e jogo: ${version}`);
