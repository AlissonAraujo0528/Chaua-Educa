#!/usr/bin/env python3
"""Deterministic packing of approved, image-generated artwork, no painting.

Keeps original authoring sheets outside the published app. Crops alpha bounds,
registers food centers and masks water to the unchanged tree silhouettes.
Run from any directory: python scripts/build_runtime_art.py
"""
from pathlib import Path
import json, hashlib
from PIL import Image, ImageChops

ROOT=Path(__file__).resolve().parents[1]
SRC=ROOT/'art-source/runtime'
OUT=ROOT/'Chaua-Educa-main/assets/runtime'
OUT.mkdir(parents=True,exist_ok=True)
metadata={}

def save(im,name):
    path=OUT/name
    im.save(path,'WEBP',lossless=True,method=6)
    return {'path':'../assets/runtime/'+name,'width':im.width,'height':im.height,
            'sha256':hashlib.sha256(path.read_bytes()).hexdigest()}

def pack(items,prefix):
    pages=[];frames={}
    for key,im,offset in sorted(items,key=lambda x:-x[1].height):
        w,h=im.size;placed=False
        for page in pages:
            for shelf in page['shelves']:
                if h+4<=shelf['h'] and shelf['x']+w+4<=1024:
                    x,y=shelf['x']+2,shelf['y']+2;shelf['x']+=w+4;placed=True;break
            if not placed and page['height']+h+4<=1024:
                x,y=2,page['height']+2;page['shelves'].append({'x':w+4,'y':page['height'],'h':h+4});page['height']+=h+4;placed=True
            if placed:break
        if not placed:
            page={'im':Image.new('RGBA',(1024,1024)),'height':h+4,'shelves':[{'x':w+4,'y':0,'h':h+4}]};pages.append(page);x,y=2,2
        page['im'].paste(im,(x,y));frames[key]={'page':pages.index(page),'rect':[x,y,w,h],'offset':offset}
    defs=[]
    for i,page in enumerate(pages):
        im=page['im'].crop((0,0,1024,min(1024,((page['height']+15)//16)*16)))
        defs.append(save(im,f'{prefix}-{i+1}.webp'))
    return {'pages':defs,'frames':frames}

foods=Image.open(SRC/'foods.webp').convert('RGBA')
atlas=Image.new('RGBA',(1024,768));foodFrames=[]
for slot in range(12):
    crops=[]
    for frame in range(4):
        cell=slot*4+frame;col,row=cell%8,cell//8
        im=foods.crop((col*foods.width//8,row*foods.height//6,(col+1)*foods.width//8,(row+1)*foods.height//6))
        bbox=im.getchannel('A').point(lambda a:255 if a>12 else 0).getbbox()
        if not bbox:raise ValueError(f'Empty food {slot}/{frame}')
        crops.append(im.crop(bbox))
    scale=min(108/max(im.width for im in crops),108/max(im.height for im in crops))
    rects=[]
    for frame,im in enumerate(crops):
        im=im.resize((max(1,round(im.width*scale)),max(1,round(im.height*scale))),Image.Resampling.LANCZOS)
        cell=slot*4+frame;x,y=(cell%8)*128,(cell//8)*128
        atlas.paste(im,(x+(128-im.width)//2,y+(128-im.height)//2))
        rects.append([x,y,128,128])
    foodFrames.append(rects)
metadata['foods']={'pages':[save(atlas,'foods.webp')],'frames':foodFrames}

wet=[]
for kind,basePath,cell in [('lower','v7/trees-lower.webp',512),('upper','v7/trees-upper.webp',512),('variants','v9/tree-variants.webp',256)]:
    base=Image.open(ROOT/'Chaua-Educa-main/assets'/basePath).convert('RGBA')
    im=Image.open(SRC/f'wet-{kind}.webp').convert('RGBA').resize(base.size,Image.Resampling.LANCZOS)
    im.putalpha(ImageChops.multiply(im.getchannel('A'),base.getchannel('A')))
    for i in range(4):
        tile=im.crop(((i%2)*cell,(i//2)*cell,(i%2+1)*cell,(i//2+1)*cell));box=tile.getbbox()
        if not box:raise ValueError('Empty wet overlay')
        wet.append((f'{kind}-{i}',tile.crop(box),list(box[:2])))
metadata['wet']=pack(wet,'wet')

fx=[]
water=Image.open(SRC/'water-fx.webp').convert('RGBA')
for i in range(12):
    cell=i if i<8 else i+4 # splash dissipates in the final row
    tile=water.crop(((cell%4)*water.width//4,(cell//4)*water.height//4,(cell%4+1)*water.width//4,(cell//4+1)*water.height//4))
    box=tile.getchannel('A').point(lambda a:255 if a>8 else 0).getbbox();tile=tile.crop(box)
    tile.thumbnail((64,64),Image.Resampling.LANCZOS)
    fx.append((f'water-{i}',tile,[0,0]))
shedding=Image.open(SRC/'snow-shedding.webp').convert('RGBA')
for t in range(6):
    for i in range(4):
        tile=shedding.crop((t*1024+(i%2)*512,(i//2)*512,t*1024+(i%2+1)*512,(i//2+1)*512));box=tile.getbbox()
        if box:fx.append((f'snow-{t}-{i}',tile.crop(box),list(box[:2])))
metadata['fx']=pack(fx,'weather-fx')
managed={Path(page['path']).name for family in metadata.values() for page in family['pages']}
for pattern in ['foods.webp','wet-*.webp','weather-fx-*.webp']:
    for old in OUT.glob(pattern):
        if old.name not in managed:old.unlink()
js='// Generated by scripts/build_runtime_art.py. Do not hand edit.\nexport const RUNTIME_ART='+json.dumps(metadata,separators=(',',':'))+';\n'
(ROOT/'Chaua-Educa-main/js/runtime-art-data.mjs').write_text(js)
print('Runtime pages:',[(x['path'],x['width'],x['height'])for v in metadata.values()for x in v['pages']])
